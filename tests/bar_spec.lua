local mock = require("tests.wow_mock")

describe("BarLogic", function()
	local B, s

	before_each(function()
		mock.install()
		B = mock.loadAddon(".").BarLogic
		s = B.new()
	end)

	it("starts waiting: timeline fill from the cast, a half-alpha gate at 600 ms, world latency", function()
		B.start(s, 10, { home = 30, world = 95 }, false)
		assert.equal("waiting", s.phase)
		assert.near(0.695, s.timeout, 1e-9)
		local v = B.view(s, 10.14)
		assert.near(0.1, v.fill, 1e-9) -- 140 of 1400 ms
		assert.near(0.6 / 1.4, v.gate, 1e-9)
		assert.is_false(v.gateSolid)
		assert.equal("Wait", v.label)
		assert.equal("violet", v.color)
		assert.equal("95 ms", v.latency)
		assert.equal("", v.sub)
		assert.same({}, v.pips)
		assert.equal(1, s.counters.started)
	end)

	it("shows ? for an unknown world latency and uses a 600 ms timeout", function()
		B.start(s, 10, { home = 30 }, false)
		assert.near(0.6, s.timeout, 1e-9)
		assert.equal("? ms", B.view(s, 10).latency)
	end)

	it("fills amber with a warning when the player moved at the cast", function()
		B.start(s, 10, {}, true)
		local v = B.view(s, 10.1)
		assert.equal("amber", v.color)
		assert.equal("Moving", v.label)
		assert.equal("Cast while moving: the loot window rarely opens", v.sub)
	end)

	it("snaps the gate solid to open + 150 ms per slot + 40 ms and lays one pip per slot", function()
		B.start(s, 10, {}, false)
		assert.is_true(B.onWindow(s, 10.25, 2, 0.15))
		assert.equal("looting", s.phase)
		local v = B.view(s, 10.3)
		assert.is_true(v.gateSolid)
		assert.near((0.25 + 0.3 + 0.04) / 1.4, v.gate, 1e-9)
		assert.equal(2, #v.pips)
		assert.near(0.4 / 1.4, v.pips[1].pos, 1e-9)
		assert.near(0.55 / 1.4, v.pips[2].pos, 1e-9)
		assert.is_false(v.pips[1].taken)
		B.onSlotCleared(s, 1)
		assert.is_true(B.view(s, 10.4).pips[1].taken)
	end)

	it("turns yellow 'Open now' at the close with everything taken and drains over 3 s", function()
		B.start(s, 10, {}, false)
		B.onWindow(s, 10.25, 1, 0.15)
		assert.is_true(B.onClosed(s, 10.5, 0))
		assert.equal("ready", s.phase)
		local v = B.view(s, 10.5)
		assert.is_true(v.yellow)
		assert.equal("Open now", v.label)
		assert.equal(1, v.fill)
		assert.near(0.5, B.view(s, 12).fill, 1e-9)
		assert.equal("ready", B.tick(s, 13.49))
		assert.equal("idle", B.tick(s, 13.5))
		assert.equal(1, s.counters.lootClosed)
		assert.equal(1, s.counters.ready)
	end)

	it("drains over the configured time", function()
		s.drain = 5
		B.start(s, 10, {}, false)
		B.onWindow(s, 10.25, 1, 0.15)
		B.onClosed(s, 10.5, 0)
		assert.near(0.8, B.view(s, 11.5).fill, 1e-9)
	end)

	it("a press on the ready bar is 'Opened' with the delay after the bar turned, and keeps draining", function()
		B.start(s, 10, {}, false)
		B.onWindow(s, 10.25, 1, 0.15)
		B.onClosed(s, 10.5, 0)
		B.onPress(s, 10.62)
		assert.equal("opened", s.phase)
		local v = B.view(s, 10.7)
		assert.equal("Opened", v.label)
		assert.equal("Loot in. Opened 120 ms after the bar turned.", v.sub)
		assert.is_true(v.yellow)
		assert.equal(1, s.counters.opened)
		assert.equal("idle", B.tick(s, 13.5))
	end)

	it("a press before ready is 'Too early': red, a tick at the press, ms before the gate", function()
		B.start(s, 10, {}, false)
		B.onWindow(s, 10.25, 2, 0.15)
		B.onPress(s, 10.4)
		assert.equal("early", s.phase)
		local v = B.view(s, 10.45)
		assert.equal("red", v.color)
		assert.equal("Too early", v.label)
		assert.near(0.4 / 1.4, v.tick, 1e-9)
		assert.equal("Opened 190 ms early. Loot lost.", v.sub) -- gate 590 ms, press 400 ms
		assert.equal(1, s.counters.early)
		-- the close that follows does not count as a loot release
		assert.is_false(B.onClosed(s, 10.41, 1))
		assert.equal(0, s.counters.lootClosed)
		assert.equal("idle", B.tick(s, 10.4 + B.HOLD + 0.01))
	end)

	it("without a window by the timeout: 'No loot, open now', counted as a timeout", function()
		B.start(s, 10, { world = 100 }, false)
		assert.equal("waiting", B.tick(s, 10.69))
		assert.equal("ready", B.tick(s, 10.71))
		assert.equal("No loot, open now", B.view(s, 10.71).label)
		assert.equal(1, s.counters.timeout)
		assert.is_false(B.onWindow(s, 10.8, 1, 0.15))
	end)

	it("says loot was left when the window closes with slots in it", function()
		B.start(s, 10, {}, false)
		B.onWindow(s, 10.25, 3, 0.15)
		B.onClosed(s, 10.5, 2)
		assert.equal("left", s.phase)
		local v = B.view(s, 10.5)
		assert.equal("Loot left", v.label)
		assert.equal("The window closed with 2 left.", v.sub)
		assert.equal(1, s.counters.left)
	end)

	it("gives up on a window open longer than STALE", function()
		B.start(s, 10, {}, false)
		B.onWindow(s, 10.25, 1, 0.15)
		assert.equal("stale", B.tick(s, 10.25 + B.STALE + 0.01))
		assert.equal(1, s.counters.stale)
	end)

	it("caps the fill at the full width", function()
		B.start(s, 10, {}, false)
		B.onWindow(s, 10.25, 9, 0.15)
		assert.equal(1, B.view(s, 12).fill)
	end)
end)

describe("Bar on the recorder's events", function()
	local ns
	local MOB = "Creature-0-1-0-1-2585-0000ABCD"

	before_each(function()
		mock.install()
		ns = mock.loadAddon(".")
		mock.target = { guid = MOB, name = "Stromgarde Soldier", level = 38, dead = false }
	end)

	local function cast(castGUID, spellID)
		mock.fire("UNIT_SPELLCAST_SENT", "player", "Stromgarde Soldier", castGUID, spellID or 921)
		mock.advance(0.1)
		mock.fire("UNIT_SPELLCAST_SUCCEEDED", "player", castGUID, spellID or 921)
	end

	it("goes Wait -> Open now -> Opened on an auto-looted pocket, and the selftest counts it", function()
		cast("Cast-1")
		assert.equal("waiting", ns.Bar.state.phase)
		assert.is_true(ns.Bar.view:IsShown())
		assert.equal("Wait", ns.Bar.view.label:GetText())
		assert.equal("60 ms", ns.Bar.view.lat:GetText())
		mock.advance(0.15)
		mock.loot = { mock.moneySlot(MOB, 87), mock.itemSlot(MOB, 5432) }
		mock.fire("LOOT_READY", true)
		mock.fire("LOOT_OPENED", true)
		assert.equal("looting", ns.Bar.state.phase)
		-- opened 150 ms after SUCCEEDED, + 2 x autoLootRate 150 ms (from the CVar) + 40 ms
		assert.near(0.15 + 0.3 + 0.04, ns.Bar.state.gate, 1e-6)
		mock.fire("LOOT_SLOT_CLEARED", 1)
		mock.fire("LOOT_SLOT_CLEARED", 2)
		assert.is_true(ns.Bar.state.taken[2])
		mock.advance(0.3)
		mock.fire("LOOT_CLOSED")
		assert.equal("ready", ns.Bar.state.phase)
		assert.equal("Open now", ns.Bar.view.label:GetText())
		mock.advance(0.1)
		mock.fire("UNIT_SPELLCAST_SENT", "player", "Stromgarde Soldier", "Cast-2", 1833)
		assert.equal("opened", ns.Bar.state.phase)
		assert.equal("Loot in. Opened 100 ms after the bar turned.", ns.Bar.view.sub:GetText())
		mock.advance(3)
		ns.Bar.tick()
		assert.is_false(ns.Bar.view:IsShown())
		local st = ns.selftest.snapshot("test").bar
		assert.equal(1, st.started)
		assert.equal(1, st.lootClosed)
		assert.equal(1, st.opened)
		assert.equal(0, st.timeout)
		assert.is_true(st.enabled)
		assert.equal(3, st.drain)
		-- recording is unchanged
		assert.equal("looted", ns.Logic.classifyAttempt(ns.db.attempts[1], mock.clock))
	end)

	it("an opener while the window is open is too early", function()
		cast("Cast-1")
		mock.advance(0.15)
		mock.loot = { mock.moneySlot(MOB, 87) }
		mock.fire("LOOT_READY", true)
		mock.fire("UNIT_SPELLCAST_SENT", "player", "Stromgarde Soldier", "Cast-2", 1833)
		assert.equal("early", ns.Bar.state.phase)
		assert.equal("Too early", ns.Bar.view.label:GetText())
	end)

	it("releases with 'No loot, open now' on the timeout", function()
		cast("Cast-1")
		mock.advance(0.71) -- world latency 60 ms: timeout 660 ms
		ns.Bar.tick()
		assert.equal("ready", ns.Bar.state.phase)
		assert.equal("No loot, open now", ns.Bar.view.label:GetText())
		assert.equal(1, ns.Bar.selftest().timeout)
	end)

	it("starts from the window when it beats the cast's SUCCEEDED", function()
		mock.fire("UNIT_SPELLCAST_SENT", "player", "Stromgarde Soldier", "Cast-1", 921)
		mock.advance(0.2)
		mock.loot = { mock.moneySlot(MOB, 87) }
		mock.fire("LOOT_READY", true)
		assert.equal("looting", ns.Bar.state.phase)
		mock.fire("UNIT_SPELLCAST_SUCCEEDED", "player", "Cast-1", 921)
		assert.equal("looting", ns.Bar.state.phase)
		assert.equal(1, ns.Bar.selftest().started)
	end)

	it("clears on a target change", function()
		cast("Cast-1")
		mock.fire("PLAYER_TARGET_CHANGED")
		assert.equal("idle", ns.Bar.state.phase)
		assert.is_false(ns.Bar.view:IsShown())
	end)

	it("ignores other spells' casts and a window that is not the pocket", function()
		cast("Cast-1", 1752)
		assert.equal("idle", ns.Bar.state.phase)
		mock.target.dead = true
		mock.loot = { mock.moneySlot(MOB, 87) }
		mock.fire("LOOT_READY", true)
		assert.equal("idle", ns.Bar.state.phase)
	end)

	it("does nothing in an instance", function()
		mock.inInstance = true
		cast("Cast-1")
		assert.equal("idle", ns.Bar.state.phase)
	end)

	it("skips a secret cast GUID without an error", function()
		mock.secret["Cast-S"] = true
		cast("Cast-S")
		assert.equal("idle", ns.Bar.state.phase)
		assert.is_nil(ns.selftest.lastError)
	end)

	it("shows a secret world latency as ?", function()
		mock.latency = { 40, "s-world" }
		mock.secret["s-world"] = true
		cast("Cast-1")
		assert.equal("? ms", ns.Bar.view.lat:GetText())
	end)

	it("turns off, back on, unlocks, sets the drain and saves it in the SavedVariables", function()
		ns.Bar.slash("off")
		assert.is_false(ns.db.bar.enabled)
		cast("Cast-1")
		assert.equal("idle", ns.Bar.state.phase)
		ns.Bar.slash("unlock")
		assert.is_true(ns.db.bar.enabled)
		assert.is_false(ns.db.bar.locked)
		assert.is_true(ns.Bar.view:IsShown()) -- shown for dragging while unlocked
		ns.Bar.slash("lock")
		assert.is_true(ns.db.bar.locked)
		assert.is_false(ns.Bar.view:IsShown())
		ns.Bar.slash("drain 4.5")
		assert.equal(4.5, ns.db.bar.drain)
		assert.equal(4.5, ns.Bar.state.drain)
		assert.truthy(ns.Bar.slash("drain 99")[1]:find("between", 1, true))
		assert.truthy(ns.Bar.slash("nonsense")[1]:find("on | off", 1, true))
	end)

	it("routes /pocketlog bar to the bar", function()
		_G.SlashCmdList.POCKETLOG("bar off")
		assert.is_false(ns.db.bar.enabled)
		assert.truthy(mock.chat[#mock.chat]:find("PocketLog bar: off", 1, true))
	end)

	it("keeps the saved position, state and drain across a reload", function()
		local saved = { bar = { enabled = false, locked = false, drain = 2, point = { "TOP", "TOP", 10, -50 } } }
		mock.install()
		ns = mock.loadAddon(".", saved)
		assert.is_false(ns.Bar.cfg.enabled)
		assert.equal(2, ns.Bar.state.drain)
		assert.same({ "TOP", "TOP", 10, -50 }, ns.db.bar.point)
	end)
end)
